/// Monotonically increasing fencing epoch for thread write ownership.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, TS)]
#[serde(transparent)]
#[ts(export, type = "number")]
pub struct Epoch(pub u64);

impl Epoch {
    /// Returns the next monotonically incremented epoch (`epoch + 1`).
    pub const fn next(self) -> Self {
        Self(self.0.saturating_add(1))
    }
}

/// Monotonically increasing per-boot event sequence number.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, TS)]
#[serde(transparent)]
#[ts(export, type = "number")]
pub struct Seq(pub u64);

impl Seq {
    /// Returns the next monotonically incremented sequence number.
    pub const fn next(self) -> Self {
        Self(self.0.saturating_add(1))
    }
}

/// Unix epoch timestamp in milliseconds (JSON-safe 53-bit integer in TypeScript).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, TS)]
#[serde(transparent)]
#[ts(export, type = "number")]
pub struct TimestampMs(pub i64);

macro_rules! impl_string_id {
    ($ty:ty) => {
        impl From<String> for $ty {
            fn from(value: String) -> Self {
                Self(value)
            }
        }

        impl From<&str> for $ty {
            fn from(value: &str) -> Self {
                Self(value.to_owned())
            }
        }

        impl AsRef<str> for $ty {
            fn as_ref(&self) -> &str {
                &self.0
            }
        }

        impl std::fmt::Display for $ty {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                self.0.fmt(f)
            }
        }
    };
}

impl_string_id!(ThreadId);
impl_string_id!(TurnId);
impl_string_id!(LeaseId);
impl_string_id!(MailboxMessageId);
impl_string_id!(EventId);
impl_string_id!(BootId);
impl_string_id!(PtyId);
