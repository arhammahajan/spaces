#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PATH="$HOME/.cargo/bin:$HOME/.bun/bin:$PATH"

GEN_DIR="$ROOT_DIR/packages/types/src/generated"
INDEX_FILE="$ROOT_DIR/packages/types/src/index.ts"
CHECK_MODE=0

if [[ "${1:-}" == "--check" ]]; then
  CHECK_MODE=1
fi

rm -rf "$GEN_DIR"
mkdir -p "$GEN_DIR"

TS_RS_EXPORT_DIR="$GEN_DIR" cargo test -p spaces-types --lib export_bindings -- --nocapture

{
  echo "// This file is auto-generated by scripts/generate-types.sh. Do not edit manually."
  echo ""
  echo "export const PROTOCOL_VERSION = 1 as const;"
  echo "export const OSC_STATUS_CODE = 7501 as const;"
  echo "export const OSC_RESUME_HINT_CODE = 7577 as const;"
  echo "export const PTY_REPLAY_RING_BYTES = 1048576 as const;"
  echo "export const SPACES_CONFIG_DIR_NAME = \".spaces\" as const;"
  echo ""
  echo "export const RPC_METHODS = {"
  echo "  AUTH: \"rpc.auth\","
  echo "  DAEMON_PING: \"daemon.ping\","
  echo "  DAEMON_STATUS: \"daemon.status\","
  echo "  THREAD_SPAWN: \"thread.spawn\","
  echo "  THREAD_LIST: \"thread.list\","
  echo "  THREAD_GET: \"thread.get\","
  echo "  THREAD_CLOSE: \"thread.close\","
  echo "  TURN_SEND: \"turn.send\","
  echo "  TURN_CANCEL: \"turn.cancel\","
  echo "  LEASE_CLAIM: \"lease.claim\","
  echo "  LEASE_YIELD: \"lease.yield\","
  echo "  LEASE_HANDOFF: \"lease.handoff\","
  echo "  LEASE_STATUS: \"lease.status\","
  echo "  MAILBOX_SEND: \"mailbox.send\","
  echo "  MAILBOX_LIST: \"mailbox.list\","
  echo "  MAILBOX_ACK: \"mailbox.ack\","
  echo "  EVENT_SUBSCRIBE: \"event.subscribe\","
  echo "  EVENT_UNSUBSCRIBE: \"event.unsubscribe\","
  echo "  EVENT_TAIL: \"event.tail\","
  echo "  EVENT_PUSH: \"event.push\","
  echo "  BACKEND_EXEC: \"backend.exec\","
  echo "  BACKEND_SPACES_LIST: \"backend.spaces.list\","
  echo "  BACKEND_HOOK_DETAIL_GET: \"backend.hook_detail.get\","
  echo "  BACKEND_HARNESSES_LIST: \"backend.harnesses.list\","
  echo "  BACKEND_TELEMETRY_GET: \"backend.telemetry.get\","
  echo "  BACKEND_CONVERSATIONS_LIST: \"backend.conversations.list\","
  echo "  BACKEND_CONVERSATIONS_SEARCH: \"backend.conversations.search\","
  echo "  BACKEND_SHARED_LIST: \"backend.shared.list\","
  echo "  BACKEND_WORKTREES_LIST: \"backend.worktrees.list\","
  echo "  PTY_SPAWN: \"pty.spawn\","
  echo "  PTY_ATTACH: \"pty.attach\","
  echo "  PTY_DETACH: \"pty.detach\","
  echo "  PTY_INPUT: \"pty.input\","
  echo "  PTY_OUTPUT: \"pty.output\","
  echo "  PTY_RESIZE: \"pty.resize\","
  echo "  PTY_KILL: \"pty.kill\","
  echo "  PTY_EXIT: \"pty.exit\","
  echo "  PTY_OSC: \"pty.osc\","
  echo "} as const;"
  echo ""
  LC_ALL=C find "$GEN_DIR" -maxdepth 1 -name '*.ts' -printf '%f\n' | LC_ALL=C sort | while read -r fname; do
    stem="${fname%.ts}"
    echo "export type { ${stem} } from \"./generated/${stem}\";"
  done
} > "$INDEX_FILE"

if [[ "$CHECK_MODE" -eq 1 ]]; then
  cd "$ROOT_DIR"
  if ! git diff --exit-code -- packages/types/src; then
    echo "ERROR: Generated TypeScript types are out of date. Run ./scripts/generate-types.sh" >&2
    exit 1
  fi
  UNTRACKED="$(git status --porcelain -- packages/types/src | grep '^??' || true)"
  if [[ -n "$UNTRACKED" ]]; then
    echo "ERROR: Untracked generated TypeScript files detected:" >&2
    echo "$UNTRACKED" >&2
    exit 1
  fi
  echo "OK: TypeScript bindings are up to date."
fi
